<script>
  document.addEventListener('DOMContentLoaded', function() {
    // Función para actualizar el contador de notificaciones
    function actualizarContadorNotificaciones() {
        fetch('/notificaciones/contador') // Ruta para obtener el contador de notificaciones
            .then(response => response.json())
            .then(data => {
                const contadorElement = document.getElementById('contadorNotificaciones');
                if (data.contador > 0) {
                    contadorElement.textContent = data.contador > 99 ? '99+' : data.contador; // Mostrar '99+' si es mayor a 99
                    contadorElement.style.display = 'inline'; // Mostrar el contador
                } else {
                    contadorElement.style.display = 'none'; // Ocultar el contador si es 0
                }
            })
            .catch(error => console.error('Error al obtener el contador de notificaciones:', error)); 
    }

   function cargarNotificaciones() {
        fetch("{{ route('notificaciones.json') }}")
            .then(response => response.json())
            .then(data => {
               const notificaciones = Array.isArray(data) ? data : data.notifications || [];

               //console.log('Datos recibidos:', data);
               
               //console.log('estas son notificaciones?', notificaciones);
               const contenedor = document.getElementById('listaNotificaciones');
               contenedor.innerHTML = '';

            
               notificaciones.forEach(n => {
                const fecha = new Date(n.created_at);
                // Formato: 17 Feb, 11:41 AM
                const fecha_formateada = fecha.toLocaleString('es-MX', {
                    day: '2-digit', 
                    month: 'short', 
                    hour: '2-digit', 
                    minute: '2-digit', 
                    hour12: true 
                }).replace('.', '');

                const isUnread = !n.leida;

                contenedor.innerHTML += `
                    <a href="#" class="notification-item ${isUnread ? 'unread' : ''}">
                        <img class="notif-avatar" src="/${n.data.foto_perfil_asignador || '../assets/images/default-avatar.png'}" alt="User">
                        <div class="notif-content">
                            <span class="notif-user">
                                ${n.data.titulo}
                            </span>
                            <span class="notif-time">
                                ${fecha_formateada}
                            </span>
                        </div>
                    </a>
                `;
            });

            // Mensaje si está vacío
            if (notificaciones.length === 0) {
                contenedor.innerHTML = `
                    <div class="empty-state">
                        <i class="far fa-bell-slash d-block mb-2" style="font-size: 1.5rem;"></i>
                        <p class="mb-0 small">Todo al día por aquí</p>
                    </div>`;
            }
        });
      }

    // Actualizar el contador cada 3 segundos (3000 ms)
    //setInterval(() => {
    //    actualizarContadorNotificaciones();
    //    cargarNotificaciones();
    //}, 3000);

    // Actualizar el contador al cargar la página
    actualizarContadorNotificaciones();
    cargarNotificaciones();
    
});
</script>